//============================================================
// AD9238 双通道 ADC 接口
//
// 功能：
// 1. 在 adc_clk_i 上升沿同时采集 CH_A、CH_B 两路 12 位数据
// 2. 输出：
//      ch_a_o   = CH_A
//      ch_b_o   = CH_B
//      sample_o = {CH_B, CH_A}
// 3. 采集开始后经过 PIPELINE_DELAY 个时钟周期，
//    sample_valid_o 置 1
// 4. 采集 A/B 两路 OTR 状态
// 5. 不使用 ADC enable 信号
// 6. 不使用 locked 信号
//============================================================

module adc9238_if #(
    parameter integer PIPELINE_DELAY = 8
)(
    //========================================================
    // ADC 时钟与 FPGA 复位
    //========================================================
    input  wire        adc_clk_i,
    input  wire        rst_n_i,

    //========================================================
    // AD9238 -> FPGA
    // A/B 两路 12 位数据
    //========================================================
    input  wire [11:0] adc_a_data_i,
    input  wire [11:0] adc_b_data_i,

    //========================================================
    // AD9238 -> FPGA
    // A/B 两路 OTR
    //========================================================
    input  wire        adc_otr_a_i,
    input  wire        adc_otr_b_i,

    //========================================================
    // FPGA 内部输出
    //========================================================
    output reg  [11:0] ch_a_o,
    output reg  [11:0] ch_b_o,

    // sample_o[23:12] = CH_B
    // sample_o[11:0]  = CH_A
    output wire [23:0] sample_o,

    output reg         sample_valid_o,

    //========================================================
    // OTR 输出
    //========================================================
    output reg         otr_a_o,
    output reg         otr_b_o
);

    //========================================================
    // ADC 预热计数器
    //========================================================
    reg [15:0] warmup_count;

    //========================================================
    // A/B 两路数据打包
    //========================================================
    assign sample_o = {ch_b_o, ch_a_o};

    //========================================================
    // ADC 数据采集
    //========================================================
    always @(posedge adc_clk_i or negedge rst_n_i) begin

        if (!rst_n_i) begin

            ch_a_o         <= 12'd0;
            ch_b_o         <= 12'd0;

            otr_a_o        <= 1'b0;
            otr_b_o        <= 1'b0;

            sample_valid_o <= 1'b0;

            warmup_count   <= 16'd0;

        end
        else begin

            //================================================
            // 每一个 ADC 时钟上升沿采集 A/B 两路数据
            //================================================
            ch_a_o <= adc_a_data_i;
            ch_b_o <= adc_b_data_i;

            //================================================
            // 同时采集 A/B 两路 OTR
            //================================================
            otr_a_o <= adc_otr_a_i;
            otr_b_o <= adc_otr_b_i;

            //================================================
            // ADC 数据预热
            //================================================
            if (PIPELINE_DELAY == 0) begin

                sample_valid_o <= 1'b1;

            end
            else if (warmup_count < PIPELINE_DELAY) begin

                warmup_count   <= warmup_count + 1'b1;
                sample_valid_o <= 1'b0;

            end
            else begin

                sample_valid_o <= 1'b1;

            end

        end
    end

endmodule